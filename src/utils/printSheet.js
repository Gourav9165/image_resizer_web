/**
 * Passport Photo Maker - 4x6 Multi-Photo Print Sheet Generator
 * Generates a standard 4x6 inch (1200 x 1800 px at 300 DPI) photo sheet
 * tiling 6 passport photos (3.5 x 4.5 cm each) with scissor cut guidelines.
 */

export async function generate4x6PrintSheet(sourceUrlOrImg) {
  // 1. Resolve source image
  let img;
  if (typeof sourceUrlOrImg === 'string') {
    img = new Image();
    img.crossOrigin = 'anonymous';
    await new Promise((resolve, reject) => {
      img.onload = resolve;
      img.onerror = (e) => reject(new Error('Failed to load image for print sheet: ' + e));
      img.src = sourceUrlOrImg;
    });
  } else {
    img = sourceUrlOrImg;
  }

  // 2. 4x6 inch canvas at 300 DPI (1200 x 1800 px)
  const SHEET_WIDTH = 1200;
  const SHEET_HEIGHT = 1800;
  const PHOTO_WIDTH = 413; // 3.5 cm at 300 DPI
  const PHOTO_HEIGHT = 531; // 4.5 cm at 300 DPI

  const canvas = document.createElement('canvas');
  canvas.width = SHEET_WIDTH;
  canvas.height = SHEET_HEIGHT;
  const ctx = canvas.getContext('2d', { alpha: false });

  // 3. Fill clean white photographic paper background
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, SHEET_WIDTH, SHEET_HEIGHT);
  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = 'high';

  // 4. Grid configuration: 2 columns x 3 rows = 6 photos
  const LEFT_MARGIN = 147;
  const COL_GAP = 80;
  const TOP_MARGIN = 58;
  const ROW_GAP = 45;

  const positions = [];
  for (let row = 0; row < 3; row++) {
    for (let col = 0; col < 2; col++) {
      const x = LEFT_MARGIN + col * (PHOTO_WIDTH + COL_GAP);
      const y = TOP_MARGIN + row * (PHOTO_HEIGHT + ROW_GAP);
      positions.push({ x, y });
    }
  }

  // 5. Draw photos, borders, and corner cutting guides
  positions.forEach(({ x, y }) => {
    // Draw Photo
    ctx.drawImage(img, x, y, PHOTO_WIDTH, PHOTO_HEIGHT);

    // Subtle 1px photo border for easy scissor alignment
    ctx.strokeStyle = '#D1D5DB';
    ctx.lineWidth = 1;
    ctx.strokeRect(x, y, PHOTO_WIDTH, PHOTO_HEIGHT);

    // Subtle corner cut ticks extending into margins
    ctx.strokeStyle = '#9CA3AF';
    ctx.lineWidth = 0.75;
    const tickLen = 10;

    // Top-Left
    ctx.beginPath();
    ctx.moveTo(x - tickLen, y);
    ctx.lineTo(x, y);
    ctx.moveTo(x, y - tickLen);
    ctx.lineTo(x, y);
    ctx.stroke();

    // Top-Right
    ctx.beginPath();
    ctx.moveTo(x + PHOTO_WIDTH, y);
    ctx.lineTo(x + PHOTO_WIDTH + tickLen, y);
    ctx.moveTo(x + PHOTO_WIDTH, y - tickLen);
    ctx.lineTo(x + PHOTO_WIDTH, y);
    ctx.stroke();

    // Bottom-Left
    ctx.beginPath();
    ctx.moveTo(x - tickLen, y + PHOTO_HEIGHT);
    ctx.lineTo(x, y + PHOTO_HEIGHT);
    ctx.moveTo(x, y + PHOTO_HEIGHT);
    ctx.lineTo(x, y + PHOTO_HEIGHT + tickLen);
    ctx.stroke();

    // Bottom-Right
    ctx.beginPath();
    ctx.moveTo(x + PHOTO_WIDTH, y + PHOTO_HEIGHT);
    ctx.lineTo(x + PHOTO_WIDTH + tickLen, y + PHOTO_HEIGHT);
    ctx.moveTo(x + PHOTO_WIDTH, y + PHOTO_HEIGHT);
    ctx.lineTo(x + PHOTO_WIDTH, y + PHOTO_HEIGHT + tickLen);
    ctx.stroke();
  });

  // 6. Draw subtle header & footer watermarks for print alignment
  ctx.fillStyle = '#9CA3AF';
  ctx.font = '500 12px sans-serif';
  ctx.textAlign = 'center';
  ctx.fillText(
    '✂️ Cut along lines • 4×6 inch (10×15 cm) Photo Paper • 300 DPI True Resolution',
    SHEET_WIDTH / 2,
    30
  );
  ctx.fillText(
    '6× Passport Photos (3.5 × 4.5 cm) • Generated by Image Resizer Web (imageresizerweb.com)',
    SHEET_WIDTH / 2,
    SHEET_HEIGHT - 20
  );

  // 7. Export high-quality JPEG blob (Quality: 0.98 for print fidelity)
  const blob = await new Promise((resolve) => {
    canvas.toBlob(resolve, 'image/jpeg', 0.98);
  });
  const url = URL.createObjectURL(blob);

  return {
    blob,
    url,
    width: SHEET_WIDTH,
    height: SHEET_HEIGHT,
    sizeKB: Math.round((blob.size / 1024) * 10) / 10,
    photoCount: 6,
  };
}

/**
 * Trigger browser print dialog directly for the 4x6 sheet
 */
export function printDirectly(sheetUrl) {
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Pop-up blocked. Please allow pop-ups to print directly or download the sheet.');
    return;
  }

  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
      <head>
        <title>Print Passport Photo Sheet (4x6 inch)</title>
        <style>
          @page {
            size: 4in 6in;
            margin: 0;
          }
          body {
            margin: 0;
            padding: 0;
            display: flex;
            align-items: center;
            justify-content: center;
            background: #ffffff;
          }
          img {
            width: 4in;
            height: 6in;
            object-fit: contain;
            display: block;
          }
        </style>
      </head>
      <body>
        <img src="${sheetUrl}" onload="window.print(); window.close();" />
      </body>
    </html>
  `);
  printWindow.document.close();
}
